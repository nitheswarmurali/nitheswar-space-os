// Helper: get agencies grouped by region
export function getAgenciesByRegion(): Record<string, Agency[]> {
  const regions: Record<string, Agency[]> = {};
  for (const a of ALL_AGENCIES) {
    if (!regions[a.region]) regions[a.region] = [];
    regions[a.region].push(a);
  }
  return regions;
}

// Helper: get agencies grouped by first letter
export function getAgenciesByLetter(): Record<string, Agency[]> {
  const groups: Record<string, Agency[]> = {};
  for (const a of ALL_AGENCIES) {
    const letter = a.name[0].toUpperCase();
    if (!groups[letter]) groups[letter] = [];
    groups[letter].push(a);
  }
  return groups;
}

